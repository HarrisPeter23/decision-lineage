"""phase3b_report.py - writes reports/phase3_error_analysis.md from results/phase3/p3f_errors.json (+ the agent's hand labels of the tune-half FP_inscope)."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
O = json.loads((ROOT / "results/phase3/p3f_errors.json").read_text(encoding="utf-8"))
SPLIT = json.loads((ROOT / "results/phase3/p3f_split.json").read_text(encoding="utf-8"))
HAND = {"I01": "other decision", "I02": "other decision", "I03": "other decision", "I04": "not an event", "I05": "not an event", "I06": "unannotated real event",
        "I07": "other decision", "I08": "other decision", "I09": "not an event", "I10": "other decision", "I11": "other decision", "I12": "unannotated real event",
        "I13": "unannotated real event", "I14": "unannotated real event", "I15": "unannotated real event"}
CATS = ["FP_role", "FP_dup", "FP_outside", "FP_span", "FP_inscope", "FN_cap", "FN_span", "FN_role", "FN_cross", "FN_within"]
DESC = dict(FP_role="(b) wrong role on a gold utterance", FP_dup="(c) duplicate / split of a matched gold link", FP_outside="(a) not attached to an annotated decision",
            FP_span="boundary near-miss (within 3 utterances)", FP_inscope="attached, not near any gold link (hand-split: see below)",
            FN_cap="(d) cut by the top-4 cap (present uncapped)", FN_span="(e) span boundary only (right role within 3)", FN_role="found with the wrong role",
            FN_cross="(b) missed, cross-meeting continuation", FN_within="(a) missed, within the chain's first meeting")
L = ["# Phase 3 improvement round: error analysis of `single_pass_recap_roles_top4` on DEV (2026-11-06; agent model Opus 5.5)",
     "", "Generated by `eval/phase3b_errors.py` + `eval/phase3b_report.py` from existing outputs (no new model calls). tol 1. DEV only; TEST not opened.",
     f"Tune half: {', '.join(SPLIT['tune'])}. Check half: {', '.join(SPLIT['check'])} (seed {SPLIT['seed']}, stratified by arc). "
     "Decisions in this round are taken on the TUNE half only; the check half is reported but did not inform the choice.", "",
     "## 1. Taxonomy (counts; 'headline' = the gold link supports a why_changed / evidence_to_reconsider / full_lineage question)", "",
     "| category | meaning | tune | tune headline | check | check headline | all |", "|---|---|---|---|---|---|---|"]
for c in CATS:
    L.append(f"| {c} | {DESC[c]} | {O['tune']['counts'].get(c, 0)} | {O['tune']['headline_counts'].get(c, 0)} | {O['check']['counts'].get(c, 0)} | "
             f"{O['check']['headline_counts'].get(c, 0)} | {O['all']['counts'].get(c, 0)} |")
L += ["", f"- Wrong decision attached (a localized prediction whose own decision name is closer to the other annotated decision): "
      f"{O['all']['wrong_decision']} / {O['all']['localized']} (all 14). Not an error source in this config.",
      f"- Found but in the wrong version (Phase 4 graph, v4 + L2): {O['all']['wrong_version']} / {O['all']['tp_with_version']} true positives; "
      f"by kind: {O['all']['wrong_version_by']}. 23 of 27 are proposals, rationales, evidence or reconsiderations that occur BEFORE the first resolution, which "
      "the graph correctly places in 'no version yet' while gold files them under the version they argue for: a definitional difference, not an extraction "
      "error. About 7 / 67 (10%) are genuinely attached to another version (reconsideration 3, resolution 3, evidence 1), a Phase 4 issue.",
      f"- Missed links by role (tune): {O['tune']['fn_by_role']}.", f"- Role confusions among localized misses (all): {O['all']['fn_role_confusions']}.", "",
      "**FP_inscope, hand-split (agent-checked, NOT human; all 15 tune-half cases):** "
      + ", ".join(f"{k}: {v}" for k, v in sorted(__import__('collections').Counter(HAND.values()).items()))
      + ". Only 3 / 15 are not decision events at all (e.g. 'Around three thousand for thirty.' labelled resolution); 12 / 15 are real events that gold does not "
        "annotate. Precision is a lower bound, as stated since Phase 0.", "",
      "## 2. Per role (role-typed P / R / F1, support)", "", "| role | tune | check | all |", "|---|---|---|---|"]
for r in O["all"]["per_role"]:
    f = lambda h: "{p:.2f} / {r:.2f} / {f1:.2f} ({support})".format(**O[h]["per_role"][r])
    L.append(f"| {r} | {f('tune')} | {f('check')} | {f('all')} |")
L += ["", f"Overall role-typed F1: tune {O['tune']['f1']}, check {O['check']['f1']}, all {O['all']['f1']}.", "",
      "## 3. Per set", "", "| set | half | arc | gold | pred | TP | F1 |", "|---|---|---|---|---|---|---|"]
for s, v in O["per_set"].items():
    L.append(f"| {s} | {v['half']} | {v['arc']} | {v['n_gold']} | {v['n_pred']} | {v['tp']} | {v['f1']} |")
L += ["", "## 4. Quoted samples (6 per category where available, seed 0; " + str(sum(len(v) for v in O["samples"].values())) + " errors)", ""]
for c in CATS:
    xs = O["samples"].get(c, [])
    if not xs:
        continue
    L.append(f"### {c}: {DESC[c]}")
    for e in xs:
        if e["kind"] == "FP":
            g = f" | nearest gold {e['gold']['link_id']} [{e['gold']['role']}]: {e['gold']['gist'][:110]}" if e.get("gold") else ""
            L.append(f"- {e['set_id']} {e['meeting_id']} {e['idxs']} predicted [{e['role']}]: \"{e['text'][:200]}\"{g}")
        else:
            pr = f" (predicted as {e['predicted_role']})" if e.get("predicted_role") else ""
            L.append(f"- {e['set_id']} {e['meeting_id']} {e['link_id']} gold [{e['role']}]{pr}: \"{e['text'][:200]}\" | gist: {e['gist'][:110]}")
    L.append("")
L += ["## 5. What this says (tune half; decision in phase3_configs.md P3-F)",
      "- **The largest headline-relevant loss is missed rationale.** Tune rationale recall is 0.28 (13 / 18 missed): 4 tagged as evidence or proposal, 7 not found "
      "at all (4 in later meetings), 2 cut by the cap. Check half: 0.13.",
      "- **The top-4 cap is the second source of headline misses** (tune 7 / 23 FN, 4 of them resolutions). Lifting the cap was tested in P3-C and loses "
      "precision overall, so the change should keep the budget but choose links more evenly across roles.",
      "- Duplicates (5) and span near-misses (4) are small. Wrong-decision attachment is 0. 'Wrong version' is mostly a definitional difference.",
      "- FP_outside / FP_inscope are mostly real but unannotated events, so cutting them is not a priority."]
(ROOT / "reports/phase3_error_analysis.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("written", len(L), "lines")
