"""make_tables.py - writes every table of the paper from result files (tables are never typed by hand).
  python paper/make_tables.py  -> paper/tables/*.tex
DEV tables come from results/lineage_f1_dev.json (pre-freeze, for information).
TEST tables come from results/phase7/h1_tests.json. Until that file exists, each TEST table is written as a clearly marked PLACEHOLDER.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "paper/tables"
NAMES = {"lineage": "Ours", "mine": "Ours", "vector_rag": "Vector RAG", "evowiki_style": "EvoWiki-style", "graphiti": "Graphiti"}
ABL = {"lineage": "Full system", "lineage:no_typing": "No role typing", "lineage:no_conflict_resolution": "No conflict resolution",
       "lineage:static_graph": "Static graph"}


def ci(v):
    return f"{v[0]:.3f} [{v[1][0]:.2f}, {v[1][1]:.2f}]"


def placeholder(name, caption, cols):
    return (f"% PLACEHOLDER: generated by paper/make_tables.py; filled from results/phase7/h1_tests.json once TEST pool-1 scoring is done.\n"
            f"\\begin{{table}}[t]\\centering\\caption{{{caption}}}\\label{{tab:{name}}}\n"
            f"\\begin{{tabular}}{{l{'c' * (len(cols) - 1)}}}\\toprule\n" + " & ".join(cols) + r" \\ \midrule" + "\n"
            + r"\multicolumn{" + str(len(cols)) + r"}{c}{\TBD{TEST table, not yet computed}} \\" + "\n\\bottomrule\\end{tabular}\\end{table}\n")


def dev_tables():
    d = json.loads((ROOT / "results/lineage_f1_dev.json").read_text(encoding="utf-8"))
    L = [r"\begin{table}[t]\centering", r"\caption{DEV (14 sets, pool size 1, headline questions, $n=40$): cited-lineage F1, precision, recall and recall@$k$ "
         r"with 95\% bootstrap CIs over sets (1,000 resamples). Pre-freeze, for information only.}\label{tab:dev_f1}",
         r"\resizebox{\columnwidth}{!}{\begin{tabular}{lcccc}\toprule", r"System & F1 & Precision & Recall & Recall@$k$ \\ \midrule"]
    for k, v in d["cited"].items():
        s = k.split("@")[0]
        if s in NAMES and k.endswith("@k1"):
            L.append(f"{NAMES[s]} & {ci(v['f1'])} & {v['p'][0]:.3f} & {v['r'][0]:.3f} & {v['r_at_k'][0]:.3f} \\\\")
    L += [r"\bottomrule\end{tabular}}\end{table}"]
    (OUT / "dev_f1.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    A = [r"\begin{table}[t]\centering", r"\caption{DEV ablations at the retrieval level (cited answers would need GPU on DEV): retrieved-lineage F1, precision "
         r"and recall with 95\% CIs over sets. All CIs overlap.}\label{tab:dev_abl}", r"\resizebox{\columnwidth}{!}{\begin{tabular}{lccc}\toprule",
         r"Configuration & F1 & Precision & Recall \\ \midrule"]
    for k, v in d["retrieved"].items():
        s = k.split("@")[0]
        if s in ABL and k.endswith("@k1"):
            A.append(f"{ABL[s]} & {ci(v['f1'])} & {v['p'][0]:.3f} & {v['r'][0]:.3f} \\\\")
    A += [r"\bottomrule\end{tabular}}\end{table}"]
    (OUT / "dev_ablations.tex").write_text("\n".join(A) + "\n", encoding="utf-8")


def test_tables():
    f = ROOT / "results/phase7/h1_tests.json"
    if not f.exists():
        (OUT / "test_primary.tex").write_text(placeholder("test_primary", "TEST (22 sets, pool size 1, headline questions): primary H1 test, cited-lineage F1, "
                                                          "paired bootstrap over sets (10,000 resamples), Holm over 2 tests.",
                                                          ["Ours vs", r"$\Delta$F1 [95\% CI]", "one-sided $p$", "Holm threshold", "$H_0$ rejected"]), encoding="utf-8")
        (OUT / "test_means.tex").write_text(placeholder("test_means", "TEST means (pool size 1, headline questions) with 95\\% CIs: the four systems and the three ablations of ours.",
                                                        ["System", "F1", "P", "R", "R@$k$", "NLI supp.", "NLI prec.", "Correct"]), encoding="utf-8")
        (OUT / "test_secondary.tex").write_text(placeholder("test_secondary", "TEST secondary family (19 tests, Holm within family).",
                                                            ["Metric", "vs", r"$\Delta$ [95\% CI]", "$p$", "rejected"]), encoding="utf-8")
        (OUT / "test_ablations.tex").write_text(placeholder("test_ablations", "TEST ablations (pool size 1, headline questions).",
                                                            ["Configuration", "F1", "P", "R", "NLI supp.", "Correct"]), encoding="utf-8")
        (OUT / "test_d35.tex").write_text(placeholder("test_d35", "TEST H1 on the failure-free subset of sets (secondary analysis, D-35).",
                                                      ["Ours vs", "$n$ sets", r"$\Delta$F1 [95\% CI]", "one-sided $p$"]), encoding="utf-8")
        return
    H = json.loads(f.read_text(encoding="utf-8"))
    X = json.loads((ROOT / "results/phase7/extra_tests.json").read_text(encoding="utf-8"))
    D = json.loads((ROOT / "results/lineage_f1_dev.json").read_text(encoding="utf-8"))["cited"]
    T = lambda t: f"{t['diff']:+.2f} [{t['ci'][0]:+.2f}, {t['ci'][1]:+.2f}]"   # D-48: deltas and CIs at 2 decimals
    # primary: all 22 sets and the failure-free subset (D-35)
    L = [r"\begin{table}[t]\centering", r"\caption{TEST primary test (H1): cited-lineage F1, ours minus baseline, paired bootstrap over sets (10,000 resamples, "
         r"one-sided; raw $p$, compared with Holm thresholds over the two tests; two-sided 95\% percentile CIs; Rej.: $H_0$ rejected). Lower block: the 18 failure-free sets (secondary analysis).}\label{tab:test_primary}",
         r"\resizebox{\columnwidth}{!}{\begin{tabular}{llccc}\toprule", r"Sets & vs & $\Delta$F1 [95\% CI] & $p$ & Rej. \\ \midrule"]
    for blk, tests, n in (("all 22", H["primary"], 22), ("failure-free 18", X["d35"]["tests"], X["d35"]["n_sets"])):
        for t in tests:
            L.append(f"{blk} & {NAMES[t['vs']]} & {T(t)} & {t['p']:.4f} & {'yes' if t['reject_H0'] else 'no'} \\\\")
        if blk == "all 22":
            L.append(r"\midrule")
    L += [r"\bottomrule\end{tabular}}\end{table}"]
    (OUT / "test_primary.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    # means: systems and ablations, with DEV F1 for the DEV-to-TEST drop and H2 correctness
    M, A, H2 = H["means"], X["ablations"]["means"], X["h2_lookup_asof_correctness"]
    dev = {"mine": "lineage@k1", "vector_rag": "vector_rag@k1", "evowiki_style": "evowiki_style@k1", "graphiti": "graphiti@k1"}
    rows = [("Ours (full)", "mine", M["mine"]), ("Vector RAG", "vector_rag", M["vector_rag"]), ("EvoWiki-style", "evowiki_style", M["evowiki_style"]),
            ("Graphiti", "graphiti", M["graphiti"]), None, ("\\quad no role typing", "no_typing", A["no_typing"]),
            ("\\quad no conflict resolution", "no_conflict_resolution", A["no_conflict_resolution"]), ("\\quad static graph", "static_graph", A["static_graph"])]
    L = [r"\begin{table}[t]\centering", r"\caption{TEST means on the 65 headline questions (pool size 1; 95\% CIs over sets for F1): cited-lineage F1, precision (P), "
         r"recall (R), NLI-accepted claim rate (conservative), answer correctness (Cor.); H2: exact-match correctness on the 66 lookup and as-of questions; DEV: DEV F1. Rows "
         r"below the line are ablations of ours (descriptive).}\label{tab:test_means}",
         r"\resizebox{\columnwidth}{!}{\begin{tabular}{lccccccc}\toprule", r"System & F1 [CI] & P & R & NLI & Cor. & H2 & DEV \\ \midrule"]
    for r in rows:
        if r is None:
            L.append(r"\midrule")
            continue
        name, key, m = r
        devf = f"{D[dev[key]]['f1'][0]:.3f}" if key in dev else "--"
        L.append(f"{name} & {ci(m['f1'])} & {m['p'][0]:.3f} & {m['r'][0]:.3f} & {m['nli_supported'][0]:.3f} & {m['correct'][0]:.3f} & {H2[key][0]:.3f} & {devf} \\\\")
    L += [r"\bottomrule\end{tabular}}\end{table}"]
    (OUT / "test_means.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    # secondary family (supplementary)
    L = [r"\begin{table}[t]\centering\caption{TEST secondary family (19 tests; Holm within the family).}\label{tab:test_secondary}",
         r"\resizebox{\columnwidth}{!}{\begin{tabular}{llccc}\toprule", r"Metric & vs & $\Delta$ [95\% CI] & $p$ & Rej. \\ \midrule"]
    for t in H["secondary"]:
        L.append(f"{t['metric'].replace('_', '-')} & {NAMES[t['vs']]} & {T(t)} & {t['p']:.4f} & {'yes' if t['reject_H0'] else 'no'} \\\\")
    L += [r"\bottomrule\end{tabular}}\end{table}"]
    (OUT / "test_secondary.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    for stale in ("test_ablations.tex", "test_d35.tex"):          # merged into test_means / test_primary
        (OUT / stale).unlink(missing_ok=True)


def stage_table():
    """Post-hoc stage-loss diagnostic (D-45) from results/phase7/stage_loss.json (eval/phase7_stage_loss.py)."""
    S = json.loads((ROOT / "results/phase7/stage_loss.json").read_text(encoding="utf-8"))
    pc = lambda k: f"{100 * S[k] / S['pairs']:.1f}\\%"                                        # noqa: E731
    rows = [("Never extracted", "never_extracted", "unavailable downstream"),
            ("Extracted, cut by the top-4 cap", "cut_by_cap", "compression loses history"),
            ("Kept, not cited (retrieval + generation)", "kept_not_cited", "downstream loss"),
            ("Cited in the final answer", "cited", "localized")]
    L = [r"\begin{table}[t]\centering",
         r"\caption{Where our pipeline loses the gold lineage on TEST (post-hoc): " + f"{S['pairs']} question--link pairs from the "
         + f"{S['headline_questions']} headline questions ({S['unique_links']} unique links). Retrieval and generation are counted jointly."
         + r"}\label{tab:stage_loss}",
         r"\resizebox{\columnwidth}{!}{\begin{tabular}{lrrl}\toprule", r"Stage & Pairs & Share & Reading \\ \midrule"]   # headers already short
    L += [f"{a} & {S[k]} & {pc(k)} & {b} \\\\" for a, k, b in rows]
    L += [r"\midrule",
          rf"\multicolumn{{4}}{{l}}{{Answer level: false premise rejected in {S['false_premise_rejected']} of {S['false_premise_questions']}; "
          rf"no gold link cited in {S['answers_citing_no_gold_link']} of {S['headline_questions']} answers.}} \\",
          r"\bottomrule\end{tabular}}\end{table}"]
    (OUT / "test_stage_loss.tex").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    dev_tables()
    test_tables()
    stage_table()
    print(sorted(p.name for p in OUT.glob("*.tex")))
