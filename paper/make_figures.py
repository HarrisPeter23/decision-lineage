"""make_figures.py - writes Fig. 1 as TikZ source, generated from repository data (no scores typed by hand).
  Fig. 1 (paper/fig_example_final.tex): a worked TEST example, set_01037 why_changed (set_01037-q06). Gold chain, versions and lineage come from
          data/synth/gold/set_01037.json; the answer and its citations from results/phase7/score/lineage@test_k1/answers.jsonl; matches use the
          frozen tol-1 rule (eval/lineage_f1.match) and P/R/F1 the frozen eval/lineage_f1.score_question. The short link labels are
          abbreviations of the gold gists (LABEL below); answer sentences are shortened with ellipses only (SENT below).
          Style follows Fig. 2 (paper/fig_pipeline_final.tex): sans serif, \\scriptsize (7 pt) minimum, gray palette, role abbreviations
          P/R/E/C/Rc/Rs; matched and unmatched marks differ by shape (check vs cross).
  Fig. 2 is hand-written TikZ in paper/fig_pipeline_final.tex (not generated here).
  python paper/make_figures.py   -> paper/fig_example_final.tex
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "eval"), str(ROOT / "synthgen"), str(ROOT)]
import lineage_f1 as LF                                             # noqa: E402

OUT = ROOT / "paper/fig_example_final.tex"
SET, QID = "set_01037", "set_01037-q06"
TEST_MEAN = "0.384"                                                 # Table 2, ours (full), F1 on the 65 headline questions
ABBR = {"proposal": "P", "rationale": "R", "evidence": "E", "challenge": "C", "reconsideration": "Rc", "resolution": "Rs"}
LABEL = {"B1": "all parcels to Parcelwise, 12 months",
         "B2": "cheaper, saves about 13,500 a quarter",
         "B3": "settles on Parcelwise",
         "B4": "81% on time vs 96%; 640 late parcels",
         "B5": "late parcels cost more than the saving",
         "B6": "reopens the carrier decision",
         "B7": "regional couriers, 95% on time guaranteed",
         "B8": "decides to split Eastline / Southgate"}
VERSION = {1: "Parcelwise for all south-east parcels", 2: "split Eastline / Southgate"}
SENT = {0: "Arjun raised concerns about Parcelwise's performance \\dots only eighty-one percent on time \\dots",
        1: "Aisha \\dots decided not to change the decision based on incomplete figures \\dots"}
COLW, STEP, RX, RW = 3.6, 3.75, 11.35, 6.1                          # cm; total width 17.65 cm (fits \textwidth, like Fig. 2)
CHECK, CROSS = r"$\checkmark$", r"$\boldsymbol{\times}$"


def esc(s):
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"), ("–", "--")]:
        s = s.replace(a, b)
    return s


def fig_example():
    g = json.loads((ROOT / "data/synth/gold" / f"{SET}.json").read_text(encoding="utf-8"))
    q = next(x for x in g["questions"] if x["qid"] == QID)
    a = next(json.loads(l) for l in (ROOT / "results/phase7/score/lineage@test_k1/answers.jsonl").read_text(encoding="utf-8").splitlines()
             if l.strip() and json.loads(l)["qid"] == QID)
    inv = LF.inv_maps("1", "test")[SET]                              # gold meeting id -> pool meeting id
    back = {v: k for k, v in inv.items()}
    chain = [dict(l, meeting_id=inv[l["meeting_id"]]) for l in g["chain"]]
    lineage = [l for l in chain if l["link_id"] in q["supporting_links"]]
    cited = [(m, i) for s in a["sentences"] for m, i in s["cites"]]
    sc = LF.score_question(cited, lineage, 6)
    hit = {l["link_id"] for l in lineage if any(LF.match((m, tuple(i)), l) for m, i in cited)}

    L = [r"% fig_example_final.tex -- Fig. 1, GENERATED by paper/make_figures.py from gold and scored outputs; do not edit by hand.",
         r"% Preamble: \usepackage{tikz} \usetikzlibrary{arrows.meta,calc}; amsmath and amssymb for the check and cross marks.",
         r"\begin{tikzpicture}[font=\sffamily\scriptsize, >={Stealth[length=1.5mm]},",
         r"  link/.style={draw, line width=0.4pt, rounded corners=1.5pt, fill=white, align=left, inner sep=2pt, text width=" + f"{COLW - 0.14:.2f}cm" + "},",
         r"  gold/.style={link, line width=1.1pt, fill=gray!8},",
         r"  chip/.style={draw, line width=0.4pt, rounded corners=1pt, fill=white, inner sep=1pt, minimum width=0.42cm, minimum height=0.3cm},",
         r"  ver/.style={draw, line width=0.6pt, rounded corners=1.5pt, fill=white, align=left, inner sep=2pt},",
         r"  hitmark/.style={anchor=north east, inner sep=2pt, font=\small}]"]
    last = {}
    for k in (1, 2, 3):
        x = (k - 1) * STEP
        L.append(rf"\node[anchor=north, font=\sffamily\small\bfseries] at ({x + COLW / 2:.2f},0) {{Meeting {k}}};")
        prev = None
        for l in [l for l in g["chain"] if l["meeting"] == k]:
            lid, role = l["link_id"], l["role"]
            style = "gold" if lid in q["supporting_links"] else "link"
            at = f"({x:.2f},-0.5)" if prev is None else f"($({prev}.south west)+(0,-0.12)$)"
            body = rf"\hspace*{{0.55cm}}\textbf{{{lid} {role}}}\\{esc(l['speaker'])}: {esc(LABEL[lid])}"
            L.append(rf"\node[{style}, anchor=north west] ({lid}) at {at} {{{body}}};")
            L.append(rf"\node[chip, anchor=north west] at ($({lid}.north west)+(0.07,-0.07)$) {{{ABBR[role]}}};")
            if style == "gold":
                L.append(rf"\node[hitmark] at ({lid}.north east) {{{CHECK if lid in hit else CROSS}}};")
            prev = lid
        last[k] = prev
    # decision versions below the lowest box
    L.append(r"\path let \p1=(" + last[1] + r".south), \p2=(" + last[2] + r".south), \p3=(" + last[3] + r".south), \n1={min(\y1,\y2,\y3)} in "
             r"coordinate (low) at (0,\n1);")
    # decision versions on one row, aligned with the meetings: V1 holds until meeting 3, where V2 supersedes it
    L.append(rf"\node[ver, anchor=north west, text width={2 * STEP - 0.35:.2f}cm, minimum height=0.75cm] (v1) at ($(low)+(0,-0.18)$) "
             rf"{{\textbf{{Version V1}} (meeting 1)\\{esc(VERSION[1])}}};")
    L.append(rf"\node[ver, anchor=north west, text width={COLW - 0.14:.2f}cm, minimum height=0.75cm] (v2) at ($(v1.north west)+({2 * STEP:.2f},0)$) "
             rf"{{\textbf{{Version V2}} (meeting 3)\\{esc(VERSION[2])}}};")
    L.append(r"\draw[->, line width=0.6pt] (v1.east) -- (v2.west);")
    L.append(rf"\node[anchor=north west, align=left, text width={3 * STEP - 0.15:.2f}cm, inner sep=0pt] at ($(v1.south west)+(0,-0.15)$) "
             rf"{{Thick gray border: the question's gold lineage ({len(lineage)} links). {CHECK}~matched, {CROSS}~not matched by a cited item "
             r"(same meeting, within one utterance). Link texts abbreviate the gold gists.};")
    # question and answer panel
    rows = []
    for i, s in enumerate(a["sentences"]):
        if i not in SENT:
            continue
        refs, marks = [], []
        for m, ix in dict.fromkeys((m, tuple(ix)) for m, ix in s["cites"]):
            gh = [l["link_id"] for l in lineage if LF.match((m, ix), l)]
            refs.append(f"[M{back[m][1:]}:{ix[0]}{'--' + str(ix[-1]) if len(ix) > 1 else ''}]")
            marks.append(f"{CHECK}\\,\\textbf{{{gh[0]}}}" if gh else CROSS)
        rows.append(rf"{marks[0]} & {SENT[i]} {' '.join(refs)}\\[2pt]")
    miss = ", ".join(sorted(l["link_id"] for l in lineage if l["link_id"] not in hit))
    panel = (rf"{{\small\bfseries Question}} (why\_changed, TEST)\\ \textit{{{esc(q['question'])}}}\\[3pt]"
             rf"{{\small\bfseries Our answer and explanation (excerpt)}}\\ {esc(a['answer'])}\\[2pt]"
             r"\begin{tabular}{@{}p{0.75cm}@{}p{" + f"{RW - 0.75:.2f}" + r"cm}@{}}" + " ".join(rows)
             + rf" & \textit{{(+{len(a['sentences']) - len(SENT)} more sentences)}}\end{{tabular}}\\[2pt]"
             rf"\textbf{{{sc['n_cited']} items cited: precision {sc['p']:.2f}, recall {sc['r']:.2f} (missed {miss});\\ "
             rf"cited-lineage F1 {sc['f1']:.2f} (our TEST headline mean: {TEST_MEAN})}}")
    L.append(rf"\node[draw, line width=0.6pt, rounded corners=2pt, anchor=north west, align=left, text width={RW:.2f}cm, inner sep=3pt] "
             rf"at ({RX:.2f},0.05) {{{panel}}};")
    L.append(r"\end{tikzpicture}")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    return sc


if __name__ == "__main__":
    print("example:", fig_example(), "->", OUT.relative_to(ROOT))
